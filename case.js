const ownerOnly = new Set(["restart", "shutdown", "broadcast", "block", "unblock", "join", "leave", "setdp", "setbio", "mode"]);
const groupOnly = new Set(["kick", "add", "promote", "demote", "tagall", "hidetag", "mute", "unmute", "link", "groupinfo"]);

export async function handleMessage(sock, m) {
  if (!m?.message || m.key.fromMe) return;
  const from=m.key.remoteJid;
  const sender=m.key.participant || from;
  const raw=m.message.conversation || m.message.extendedTextMessage?.text ||
    m.message.imageMessage?.caption || m.message.videoMessage?.caption || '';
  if(!raw.startsWith(config.prefix)) return;
  const body=raw.slice(config.prefix.length).trim();
  const [command,...args]=body.split(/\s+/);
  const cmd=(command||'').toLowerCase();
  const text=body.slice(command.length).trim();
  const quoted=m.message.extendedTextMessage?.contextInfo?.quotedMessage || null;
  const mentioned=m.message.extendedTextMessage?.contextInfo?.mentionedJid || [];
  const isGroup=from.endsWith('@g.us');
  let isOwner=Boolean(config.ownerNumber && sender.replace(/\D/g,'').startsWith(config.ownerNumber));
  let isGroupAdmin=false;
  if(isGroup) {
    try {
      const meta=await sock.groupMetadata(from);
      const participant=meta.participants.find(p=>p.id===sender);
      isGroupAdmin=Boolean(participant?.admin);
      if(!isOwner && !isGroupAdmin && groupOnly.has(cmd)) return sock.sendMessage(from,{text:'Group admin only.'},{quoted:m});
    } catch {}
  }
  if(ownerOnly.has(cmd) && !isOwner) return sock.sendMessage(from,{text:'Owner only. Configure OWNER_NUMBER in .env.'},{quoted:m});
  const ctx={args,text,quoted,mentioned,isGroup,isOwner,isGroupAdmin};
  const reply=(message)=>sock.sendMessage(from,{text:String(message)},{quoted:m});
  let handler;
  switch(cmd) {
      case 'bot': handler=bot_bot; break;
      case 'ping': handler=bot_ping; break;
      case 'alive': handler=bot_alive; break;
      case 'menu': handler=bot_menu; break;
      case 'help': handler=bot_help; break;
      case 'owner': handler=bot_owner; break;
      case 'info': handler=bot_info; break;
      case 'speed': handler=bot_speed; break;
      case 'runtime': handler=bot_runtime; break;
      case 'list': handler=bot_list; break;
      case 'restart': handler=owner_restart; break;
      case 'shutdown': handler=owner_shutdown; break;
      case 'broadcast': handler=owner_broadcast; break;
      case 'block': handler=owner_block; break;
      case 'unblock': handler=owner_unblock; break;
      case 'join': handler=owner_join; break;
      case 'leave': handler=owner_leave; break;
      case 'setdp': handler=owner_setdp; break;
      case 'setbio': handler=owner_setbio; break;
      case 'mode': handler=owner_mode; break;
      case 'kick': handler=group_kick; break;
      case 'add': handler=group_add; break;
      case 'promote': handler=group_promote; break;
      case 'demote': handler=group_demote; break;
      case 'tagall': handler=group_tagall; break;
      case 'hidetag': handler=group_hidetag; break;
      case 'mute': handler=group_mute; break;
      case 'unmute': handler=group_unmute; break;
      case 'link': handler=group_link; break;
      case 'groupinfo': handler=group_groupinfo; break;
      case 'welcome': handler=auto_welcome; break;
      case 'goodbye': handler=auto_goodbye; break;
      case 'antilink': handler=auto_antilink; break;
      case 'antidelete': handler=auto_antidelete; break;
      case 'autostatus': handler=auto_autostatus; break;
      case 'autoreact': handler=auto_autoreact; break;
      case 'autotyping': handler=auto_autotyping; break;
      case 'autoread': handler=auto_autoread; break;
      case 'autobio': handler=auto_autobio; break;
      case 'autoview': handler=auto_autoview; break;
      case 'ai': handler=ai_ai; break;
      case 'gpt': handler=ai_gpt; break;
      case 'gemini': handler=ai_gemini; break;
      case 'img': handler=ai_img; break;
      case 'ask': handler=ai_ask; break;
      case 'chat': handler=ai_chat; break;
      case 'imagine': handler=ai_imagine; break;
      case 'songai': handler=ai_songai; break;
      case 'code': handler=ai_code; break;
      case 'translate': handler=ai_translate; break;
      case 'boysdp1': handler=boysdp_boysdp1; break;
      case 'boysdp2': handler=boysdp_boysdp2; break;
      case 'boysdp3': handler=boysdp_boysdp3; break;
      case 'boysdp4': handler=boysdp_boysdp4; break;
      case 'boysdp5': handler=boysdp_boysdp5; break;
      case 'boysdp6': handler=boysdp_boysdp6; break;
      case 'boysdp7': handler=boysdp_boysdp7; break;
      case 'boysdp8': handler=boysdp_boysdp8; break;
      case 'boysdp9': handler=boysdp_boysdp9; break;
      case 'boysdp10': handler=boysdp_boysdp10; break;
      case 'girlsdp1': handler=girlsdp_girlsdp1; break;
      case 'girlsdp2': handler=girlsdp_girlsdp2; break;
      case 'girlsdp3': handler=girlsdp_girlsdp3; break;
      case 'girlsdp4': handler=girlsdp_girlsdp4; break;
      case 'girlsdp5': handler=girlsdp_girlsdp5; break;
      case 'girlsdp6': handler=girlsdp_girlsdp6; break;
      case 'girlsdp7': handler=girlsdp_girlsdp7; break;
      case 'girlsdp8': handler=girlsdp_girlsdp8; break;
      case 'girlsdp9': handler=girlsdp_girlsdp9; break;
      case 'girlsdp10': handler=girlsdp_girlsdp10; break;
      case 'roast': handler=roast_roast; break;
      case 'gali': handler=roast_gali; break;
      case 'tang': handler=roast_tang; break;
      case 'wife': handler=roast_wife; break;
      case 'girl': handler=roast_girl; break;
      case 'king': handler=roast_king; break;
      case 'chup': handler=roast_chup; break;
      case 'bakwas': handler=roast_bakwas; break;
      case 'topi': handler=roast_topi; break;
      case 'mental': handler=roast_mental; break;
      case 'charsi': handler=roast_charsi; break;
      case 'pagal': handler=roast_pagal; break;
      case 'kutta': handler=roast_kutta; break;
      case 'gadha': handler=roast_gadha; break;
      case 'bewakoof': handler=roast_bewakoof; break;
      case 'bhaag': handler=roast_bhaag; break;
      case 'maar': handler=roast_maar; break;
      case 'jal': handler=roast_jal; break;
      case 'chota': handler=roast_chota; break;
      case 'bada': handler=roast_bada; break;
      case 'play': handler=download_play; break;
      case 'song': handler=download_song; break;
      case 'video': handler=download_video; break;
      case 'ytmp3': handler=download_ytmp3; break;
      case 'ytmp4': handler=download_ytmp4; break;
      case 'fb': handler=download_fb; break;
      case 'tiktok': handler=download_tiktok; break;
      case 'insta': handler=download_insta; break;
      case 'songdl': handler=download_songdl; break;
      case 'videodl': handler=download_videodl; break;
      default: return;
  }
  try { await handler(sock,{...m,reply},from,ctx); }
  catch(err) { console.error('Command error:',cmd,err); await reply('Command failed. Check bot logs and permissions.'); }
}

export function attachBot(sock) {
  sock.ev.on('messages.upsert', async event => {
    if(event.type!=='notify') return;
    for(const message of event.messages) await handleMessage(sock,message);
  });
}
